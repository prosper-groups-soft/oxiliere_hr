from django.utils.translation import gettext_lazy as _
from django.conf import settings
from django.core.validators import (
    MaxValueValidator, 
    MinValueValidator
)
from django.utils import timezone
from django.db import models
from utils_mixins.models import (
    AddressMixin, 
    BaseModelMixin
)
from utils_mixins.fn import enum_to_choices
from hr.choices import (
    DegreeEnum, 
    GenderStatus, 
    MaritalStatus, 
    RelationshipType
)


class EmployeeAddress(AddressMixin):
    """
    Primary address for an Employee.
    Just a wrapper around AddressMixin.
    """
    pass


class Employee(BaseModelMixin):
    """
    Represents an employee with structural and declarative info only.
    """
    user = models.OneToOneField(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        null=True,
        related_name="employee_account",
    )
    gender = models.CharField(
        choices=enum_to_choices(GenderStatus),
        default=GenderStatus.NOT_SPECIFIED.value,
    )
    address = models.OneToOneField(
        EmployeeAddress,
        on_delete=models.RESTRICT,
        null=True,
        blank=True,
        help_text=_("Employee primary address.")
    )
    joined_date = models.DateTimeField(default=timezone.now)
    first_name = models.CharField(max_length=75)
    middle_name = models.CharField(max_length=75, blank=True, null=True)
    last_name = models.CharField(max_length=75)
    matricule = models.CharField(
        max_length=16,
        unique=True,
        help_text=_("Unique employee identifier. Generated by service layer.")
    )
    email = models.EmailField(unique=True, null=True, blank=True)
    phone = models.CharField(max_length=13, unique=True, null=True, blank=True)
    birthdate = models.DateField(null=True, blank=True)
    is_active = models.BooleanField(default=True)
    marital_status = models.CharField(
        choices=enum_to_choices(MaritalStatus),
        default=MaritalStatus.SINGLE.value,
    )
    status = models.CharField(
        max_length=2,
        choices=[],
        default=None,
        help_text=_("Employee status (optional). Can be moved to services.")
    )
    photo = models.ImageField(
        upload_to="images/",
        default="images/user-dummy-img.jpg",
    )
    description = models.TextField(null=True, blank=True)
    can_connect = models.BooleanField(default=True)

    class Meta:
        ordering = ["last_name", "first_name"]

    def __str__(self):
        return f"{self.first_name} {self.last_name} ({self.matricule})"

    def clean(self):
        """
        Standardize string formatting.
        No business logic here (e.g., no matricule generation, no career logic).
        """
        if self.first_name:
            self.first_name = self.first_name.strip().title()
        if self.middle_name:
            self.middle_name = self.middle_name.strip().title()
        if self.last_name:
            self.last_name = self.last_name.strip().title()
        if self.email:
            self.email = self.email.strip().lower()


class EmployeeEmergencyContact(BaseModelMixin):
    """
    Emergency contact for an employee.
    """
    employee = models.ForeignKey(
        Employee,
        on_delete=models.CASCADE,
        related_name="emergency_contacts",
    )
    first_name = models.CharField(max_length=75)
    middle_name = models.CharField(max_length=128, null=True, blank=True)
    last_name = models.CharField(max_length=75)
    phone = models.CharField(max_length=13, unique=True, blank=True)
    relation = models.CharField(
        choices=enum_to_choices(RelationshipType),
        default=RelationshipType.OTHER.value,
    )
    priority = models.IntegerField(
        default=1,
        validators=[MinValueValidator(1), MaxValueValidator(10)],
    )

    class Meta:
        ordering = ["priority", "last_name"]

    def clean(self):
        if self.first_name:
            self.first_name = self.first_name.strip().title()
        if self.last_name:
            self.last_name = self.last_name.strip().title()


class EmployeeChildren(BaseModelMixin):
    """
    Child of an employee.
    Business rules such as age validation or benefits are handled in services.
    """
    parent = models.ForeignKey(
        Employee,
        on_delete=models.CASCADE,
        related_name="children",
    )
    first_name = models.CharField(max_length=75)
    middle_name = models.CharField(max_length=128, null=True, blank=True)
    last_name = models.CharField(max_length=75)
    gender = models.CharField(
        choices=enum_to_choices(GenderStatus),
        default=GenderStatus.NOT_SPECIFIED.value,
    )
    birthdate = models.DateField(null=True)

    class Meta:
        ordering = ["first_name", "-birthdate"]

    def clean(self):
        if self.first_name:
            self.first_name = self.first_name.strip().title()
        if self.last_name:
            self.last_name = self.last_name.strip().title()


class EmployeeEducation(BaseModelMixin):
    """
    Academic background for an employee.
    """
    employee = models.ForeignKey(
        Employee,
        on_delete=models.CASCADE,
        related_name="educations",
    )
    institute = models.CharField(max_length=255)
    degree = models.CharField(
        choices=enum_to_choices(DegreeEnum),
        default=DegreeEnum.NOT_SPECIFIED.value,
    )
    major = models.CharField(max_length=255)
    start_year = models.DateField()
    end_year = models.DateField()
    location = models.CharField(max_length=255)

    class Meta:
        ordering = ["-end_year", "degree"]

